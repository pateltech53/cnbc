class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *args):
        pass  # keep the terminal window quiet

    def _send(self, status, body, content_type):
        payload = body if isinstance(body, bytes) else body.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(payload)))
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        self.wfile.write(payload)

    def _send_json(self, status, payload):
        self._send(status, json.dumps(payload), "application/json; charset=utf-8")

    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        query = urllib.parse.parse_qs(parsed.query)
        path = parsed.path

        if path == "/api/quotes":
            if query.get("set", [""])[0] == "tape":
                requested = "|".join(TAPE_SYMBOLS)
            else:
                requested = query.get("symbols", ["|".join(DEFAULT_WATCHLIST)])[0]
            try:
                result = cached("q:" + requested, 15, lambda: get_quotes(requested))
                self._send_json(200, dict(ok=True, updated=time.strftime("%Y-%m-%dT%H:%M:%SZ"), **result))
            except Exception as error:
                self._send_json(502, {"ok": False, "error": str(error), "quotes": [], "warnings": []})
            return

        if path == "/api/news":
            category = query.get("category", ["top"])[0]
            limit = query.get("limit", ["30"])[0]
            try:
                result = cached("n:%s:%s" % (category, limit), 120, lambda: get_news(category, limit))
                self._send_json(200, dict(
                    ok=True,
                    updated=time.strftime("%Y-%m-%dT%H:%M:%SZ"),
                    categories=[{"slug": s, "label": f[1]} for s, f in FEEDS.items()],
                    **result,
                ))
            except Exception as error:
                self._send_json(502, {"ok": False, "error": str(error), "items": [], "warnings": []})
            return

        name = "index.html" if path == "/" else path.lstrip("/")
        if name in ASSETS:
            extension = "." + name.rsplit(".", 1)[-1]
            self._send(
                200,
                base64.b64decode(ASSETS[name]),
                CONTENT_TYPES.get(extension, "application/octet-stream"),
            )
            return

        self._send(404, "Not found", "text/plain; charset=utf-8")


def find_port(preferred=8765):
    for port in range(preferred, preferred + 40):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            if probe.connect_ex(("127.0.0.1", port)) != 0:
                return port
    return 0  # let the OS choose


def main():
    port = find_port()
    server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    port = server.server_address[1]
    url = "http://localhost:%d" % port

    print("")
    print("  CNBC Daily is running.")
    print("")
    print("  Open this in your browser:  %s" % url)
    print("  To stop it, press Ctrl+C in this window.")
    print("")

    threading.Timer(1.0, lambda: webbrowser.open(url)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n  Stopped. You can close this window.\n")
        server.shutdown()


if __name__ == "__main__":
    if sys.version_info < (3, 7):
        sys.exit("This needs Python 3.7 or newer.")
    main()
