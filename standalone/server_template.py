def http_get(url, timeout=12):
    """Plain GET with a browser user agent. Returns the body as text."""
    request = urllib.request.Request(url, headers=BROWSER_HEADERS)
    with urllib.request.urlopen(request, timeout=timeout) as response:
        charset = response.headers.get_content_charset() or "utf-8"
        return response.read().decode(charset, errors="replace")


def num(value):
    """CNBC sends numbers as display strings: '1,234.56', '+0.42', 'UNCH'."""
    if value is None:
        return None
    raw = str(value).strip()
    if not raw:
        return None
    if raw.upper() == "UNCH":
        return 0.0
    if raw.upper() in ("N/A", "NA", "--", "-"):
        return None
    cleaned = re.sub(r"[,%\s+]", "", raw)
    try:
        return float(cleaned)
    except ValueError:
        return None


def market_status_label(code):
    return {
        "REG_MKT": "Market open",
        "PRE_MKT": "Pre-market",
        "POST_MKT": "After hours",
        "MKT_CLOSED": "Market closed",
    }.get(str(code or "").upper(), "")


def sanitize_symbols(raw, limit=40):
    seen = []
    for part in re.split(r"[|,]", raw or ""):
        symbol = part.strip().upper()
        if symbol and len(symbol) <= 16 and SYMBOL_RE.match(symbol) and symbol not in seen:
            seen.append(symbol)
    return seen[:limit]


