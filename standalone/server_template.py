NAMED_ENTITIES = {
    "amp": "&", "lt": "<", "gt": ">", "quot": '"', "apos": "'", "nbsp": " ",
    "rsquo": "’", "lsquo": "‘", "ldquo": "“", "rdquo": "”",
    "mdash": "—", "ndash": "–", "hellip": "…", "trade": "™",
}


def decode_entities(text):
    def replace(match):
        code = match.group(1)
        if code.startswith("#"):
            try:
                value = int(code[2:], 16) if code[1] in "xX" else int(code[1:], 10)
                return chr(value)
            except (ValueError, OverflowError):
                return match.group(0)
        return NAMED_ENTITIES.get(code.lower(), match.group(0))

    return re.sub(r"&(#x?[0-9a-fA-F]+|[a-zA-Z]+);", replace, text)


def tag_text(block, tag):
    match = re.search(r"<%s\b[^>]*>(.*?)</%s>" % (tag, tag), block, re.S | re.I)
    if not match:
        return ""
    value = match.group(1).strip()
    cdata = re.match(r"^<!\[CDATA\[(.*?)\]\]>$", value, re.S)
    if cdata:
        value = cdata.group(1)
    value = re.sub(r"<[^>]+>", "", value)
    return re.sub(r"\s+", " ", decode_entities(value)).strip()


def parse_rss(xml):
    items = []
    for match in re.finditer(r"<item\b[^>]*>(.*?)</item>", xml, re.S | re.I):
        block = match.group(1)
        title = tag_text(block, "title")
        link = tag_text(block, "link")
        if not title or not re.match(r"^https?://", link, re.I):
            continue

        published = tag_text(block, "pubDate")
        iso = None
        if published:
            try:
                from email.utils import parsedate_to_datetime
                iso = parsedate_to_datetime(published).isoformat()
            except Exception:
                iso = None

        items.append({
            "id": tag_text(block, "guid") or link,
            "title": title,
            "link": link,
            "summary": tag_text(block, "description")[:400],
            "published": iso,
        })
    return items


def fetch_feed(slug):
    feed_id = FEEDS[slug][0]
    return parse_rss(http_get("https://www.cnbc.com/id/%s/device/rss/rss.html" % feed_id))


def get_news(slug, limit=30):
    category = slug if slug in FEEDS else "top"
    warnings, items, used = [], [], category

    try:
        items = fetch_feed(category)
    except Exception as error:
        warnings.append(str(error))

    if not items and category != "top":
        warnings.append("No stories in %s; showing Top news." % FEEDS[category][1])
        used = "top"
        try:
            items = fetch_feed("top")
        except Exception as error:
            warnings.append(str(error))

    limit = max(1, min(int(limit or 30), 60))
    return {
        "category": used,
        "label": FEEDS[used][1],
        "items": items[:limit],
        "warnings": warnings,
    }


# --------------------------------------------------------------------------
# a very small cache, so clicking Refresh does not hammer CNBC
# --------------------------------------------------------------------------

_cache = {}
_cache_lock = threading.Lock()


def cached(key, ttl_seconds, produce):
    now = time.time()
    with _cache_lock:
        hit = _cache.get(key)
        if hit and now - hit[0] < ttl_seconds:
            return hit[1]
    value = produce()
    with _cache_lock:
        _cache[key] = (now, value)
    return value


