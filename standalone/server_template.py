def normalize_quote(raw):
    extended_raw = raw.get("ExtendedMktQuote") or None
    extended = None
    if extended_raw and num(extended_raw.get("last")) is not None:
        extended = {
            "last": num(extended_raw.get("last")),
            "change": num(extended_raw.get("change")),
            "changePct": num(extended_raw.get("change_pct")),
            "label": market_status_label(extended_raw.get("type")) or "Extended hours",
        }

    return {
        "symbol": raw.get("symbol") or "",
        "name": raw.get("name") or raw.get("shortName") or raw.get("symbol") or "",
        "last": num(raw.get("last")),
        "change": num(raw.get("change")),
        "changePct": num(raw.get("change_pct")),
        "prevClose": num(raw.get("previous_day_closing")),
        "open": num(raw.get("open")),
        "high": num(raw.get("high")),
        "low": num(raw.get("low")),
        "volume": num(raw.get("volume")),
        "currency": raw.get("currencyCode"),
        "marketStatus": market_status_label(raw.get("curmktstatus")),
        "asOf": raw.get("last_timedate") or raw.get("last_time"),
        "extended": extended,
        "source": "cnbc",
    }


def fetch_cnbc_quotes(symbols):
    if not symbols:
        return []
    params = urllib.parse.urlencode({
        "symbols": "|".join(symbols),
        "requestMethod": "itv",
        "noform": "1",
        "partnerId": "2",
        "fund": "1",
        "exthrs": "1",
        "output": "json",
        "events": "1",
    })
    body = json.loads(http_get(QUOTE_URL + "?" + params))
    result = (body.get("FormattedQuoteResult") or {}).get("FormattedQuote")
    if not result:
        return []
    if isinstance(result, dict):      # a single-symbol request returns an object
        result = [result]
    return [normalize_quote(q) for q in result if q and q.get("symbol")]


def fetch_stooq_quote(symbol):
    """Backup source: end-of-day CSV. Ordinary listed shares and ETFs only."""
    if not re.match(r"^[A-Z][A-Z0-9.\-]{0,9}$", symbol):
        return None
    stooq_symbol = symbol.lower().replace(".", "-") + ".us"
    try:
        text = http_get(
            "https://stooq.com/q/d/l/?s=" + urllib.parse.quote(stooq_symbol) + "&i=d",
            timeout=8,
        )
    except Exception:
        return None

    rows = [line for line in text.strip().split("\n") if line]
    if len(rows) < 3:
        return None

    latest, previous = rows[-1].split(","), rows[-2].split(",")
    try:
        close, prev_close = float(latest[4]), float(previous[4])
    except (IndexError, ValueError):
        return None
    if prev_close == 0:
        return None

    change = close - prev_close
    def maybe(index):
        try:
            return float(latest[index])
        except (IndexError, ValueError):
            return None

    return {
        "symbol": symbol, "name": symbol,
        "last": close, "change": change, "changePct": change / prev_close * 100,
        "prevClose": prev_close, "open": maybe(1), "high": maybe(2), "low": maybe(3),
        "volume": maybe(5), "currency": "USD", "marketStatus": "End of day",
        "asOf": latest[0], "extended": None, "source": "stooq",
    }


def get_quotes(raw_symbols):
    wanted = sanitize_symbols(raw_symbols)
    if not wanted:
        return {"quotes": [], "warnings": ["No valid symbols requested."]}

    warnings, quotes = [], []
    try:
        quotes = fetch_cnbc_quotes(wanted)
    except Exception as error:
        warnings.append("CNBC quotes unavailable (%s)." % error)

    found = {q["symbol"].upper() for q in quotes}
    missing = [s for s in wanted if s not in found]

    if missing:
        backups = [fetch_stooq_quote(s) for s in missing[:25]]
        usable = [b for b in backups if b]
        if usable:
            quotes.extend(usable)
            warnings.append(
                "Showing end-of-day backup prices for %d symbol(s)." % len(usable)
            )

    order = {symbol: index for index, symbol in enumerate(wanted)}
    quotes.sort(key=lambda q: order.get(q["symbol"].upper(), 999))
    return {"quotes": quotes, "warnings": warnings}


